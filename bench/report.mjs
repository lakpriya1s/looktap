// Markdown tables from a results file:  node bench/report.mjs ios|android
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const platform = process.argv[2] || 'ios';
const R = JSON.parse(readFileSync(join(import.meta.dirname, 'results', `${platform}.json`), 'utf8'));
const tools = Object.keys(R.tools);
const steps = Object.keys(R.tools[tools[0]].steps);
const med = (a) => {
  const s = a.filter((x) => x != null).sort((x, y) => x - y);
  if (!s.length) return null;
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
};
const p90 = (a) => {
  const s = a.filter((x) => x != null).sort((x, y) => x - y);
  return s.length ? s[Math.min(s.length - 1, Math.ceil(s.length * 0.9) - 1)] : null;
};
const TURN = Number(process.env.BENCH_TURN_MS || 2000); // a model round trip per tool call, for "agent time"
const ms = (v) => (v == null ? '—' : v >= 1000 ? `${(v / 1000).toFixed(v >= 10000 ? 0 : 1)} s` : `${Math.round(v)} ms`);
const kb = (b) => (b == null ? '—' : b < 1024 ? `${b} B` : `${(b / 1024).toFixed(b < 10240 ? 1 : 0)} KB`);
const stat = (t, s) => {
  const rows = R.tools[t].steps[s] || [];
  if (!rows.length || rows[0].na) return null;
  const ok = rows.filter((r) => r.ok);
  return {
    n: rows.length, ok: ok.length,
    ms: med(rows.map((r) => r.ms)), seen: med(ok.map((r) => r.seenMs)), seen90: p90(ok.map((r) => r.seenMs)),
    dims: rows.find((r) => r.dims)?.dims, inline: rows.some((r) => r.inline),
    calls: med(rows.map((r) => r.calls)), bytes: med(rows.map((r) => r.bytes)), image: med(rows.map((r) => r.image)),
  };
};
// What a screenshot puts in the agent's context: the image inline, or only a path to a file it must then open.
const tokens = (d) => (d ? `~${Math.round((d[0] * d[1]) / 750 / 100) / 10}k tokens, ${d[0]}×${d[1]}` : null);
const shotCell = (x) => {
  if (!x) return 'n/a';
  const tk = tokens(x.dims);
  return x.bytes > 5000 || x.inline
    ? `${kb(x.bytes)} inline${tk ? ` (${tk})` : ''}`
    : `path to a ${kb(x.image)} file${tk ? ` (${tk} when opened)` : ''}`;
};
const onDevice = tools.some((t) => R.tools[t].deviceUsage);
// steps every tool can do: the like-for-like total
const common = steps.filter((s) => tools.every((t) => stat(t, s)));
const out = [];
const table = (head, rows) => {
  out.push(`| ${head.join(' | ')} |`, `|${head.map((_, i) => (i ? '---:' : '---')).join('|')}|`);
  for (const r of rows) out.push(`| ${r.join(' | ')} |`);
  out.push('');
};

const v = (t) => R.tools[t].version || t;
out.push(
  `# ${platform === 'ios' ? 'iOS' : 'Android'}: every agent mobile tool, same steps, same app`,
  '',
  `Measured ${R.meta.date.slice(0, 10)} on ${R.meta.host}, ${platform === 'ios' ? 'iPhone 14 simulator (iOS 26.0)' : 'Pixel 9a emulator (Android 16, 1080×2424 at 420 dpi)'} \`${R.meta.device}\`. ` +
    `${R.meta.runs} runs per step per tool. Raw data: [\`${platform}.json\`](${platform}.json). Generated by \`node bench/report.mjs ${platform}\`.`,
  '',
  '## How it was measured',
  '',
  `- **App:** the system Settings app (\`${platform === 'ios' ? 'com.apple.Preferences' : 'com.android.settings'}\`). No sign-in, nothing real is changed.`,
  '- **Tools:** ' + tools.map((t) => `${t} (${v(t)})`).join(', ') + '.',
  '- **Driven like an agent:** MCP servers over stdio with `tools/call`; CLIs spawned once per command; raw Appium over W3C HTTP. ' +
    'When a tool cannot act on a label, the step reads the screen first and acts on what it found, and that read counts as a call.',
  '- **Two times per step:** *answered in* is until the tool call returned; *reaction time* is until a neutral oracle saw the result on screen ' +
    `(${platform === 'ios' ? '`idb ui describe-all`, polled every ~0.4 s' : "`dumpsys`: the resumed activity, the fragments on screen and the view tree. It shows no text, so text steps are checked by what they change: the search screen's results list fills, the list moves"}). A step passes only if the oracle saw it within 8 s.`,
  '- **Context:** bytes of every tool result, as an agent receives them. Screenshots are counted apart: some tools return the image inline, others a path to a file.',
  '- **Neutral resets, not timed:** wherever a step needs a clean start (launch, swipe, scroll, fill, home, open URL, terminate), the app is force-stopped and relaunched at its first screen with plain `simctl`/`adb`, the same for every tool.',
  '- **Fair start for every tool:** the simulator is rebooted, whatever the previous tool left running is killed, and the run waits until the Mac is back at its idle CPU load.',
  ...(onDevice ? ["- **On the device:** Android tools keep helpers inside the emulator (Appium's UiAutomator2 server, Maestro's driver, looktap's helper) or run one-shot `uiautomator`, `input` and `screencap` commands there. The device's own `ps`, sampled every second, measures those; the Mac-side numbers can't see them."] : []),
  "- **CPU and RAM:** `ps` every 250 ms over the tool's whole process tree, plus helpers it leaves outside it (WebDriverAgent, Maestro's driver, looktap's helper). The oracle's own commands are left out. Setup is measured separately.",
  '- **Setup:** from starting the tool until its first screen read came back.',
  '',
);
out.push(`## Summary (${common.length} steps every tool can do: ${common.join(', ')})`, '');
table(
  ['Tool', 'Reaction time, all steps', `Agent time (+${TURN / 1000} s per call)`, 'Text returned', 'Screenshot returned', 'Tool calls', 'Passed', 'Setup', 'Tool definitions', 'RAM peak / mean', 'CPU mean', ...(onDevice ? ['On-device helpers: RAM peak / mean, CPU'] : [])],
  tools.map((t) => {
    const st = common.map((s) => stat(t, s));
    const all = steps.map((s) => stat(t, s)).filter(Boolean);
    const T = R.tools[t];
    const failedCommon = st.some((x) => x.seen == null);
    return [
      `**${t}**`,
      `${ms(st.reduce((a, x) => a + (x.seen ?? x.ms), 0))}${failedCommon ? ' †' : ''}`, // †: a step never passed; its answer time is used
      ms(st.reduce((a, x) => a + (x.seen ?? x.ms) + x.calls * TURN, 0)),
      kb(common.filter((s) => s !== 'screenshot').reduce((a, s) => a + stat(t, s).bytes, 0)),
      shotCell(stat(t, 'screenshot')),
      st.reduce((a, x) => a + x.calls, 0),
      `${all.reduce((a, x) => a + x.ok, 0)}/${all.reduce((a, x) => a + x.n, 0)}`,
      T.setupMs == null ? 'failed' : ms(T.setupMs),
      T.defsBytes ? kb(T.defsBytes) : 'none (CLI)',
      T.usage ? `${T.usage.peakRssMb} / ${T.usage.meanRssMb} MB` : '—',
      T.usage ? `${T.usage.meanCpuPct}%` : '—',
      ...(onDevice ? [!T.deviceUsage ? '—' : T.deviceUsage.peakRssMb === 0 ? 'not detected' : `${T.deviceUsage.peakRssMb} / ${T.deviceUsage.meanRssMb} MB, ${T.deviceUsage.meanCpuPct}%`] : []),
    ];
  }),
);

out.push('† A step never passed; its *answered in* time is counted instead.', '');
out.push(`*Agent time* adds ${TURN / 1000} s per tool call for the model's round trip, which the device times leave out: a tool that needs more calls costs the agent more turns.`, '');
out.push('## Reaction time per step', '', 'Median (p90) time until the result was on screen, and runs that passed.', '');
table(['Step', ...tools], steps.map((s) => [s, ...tools.map((t) => {
  const x = stat(t, s);
  if (!x) return 'n/a';
  return x.seen == null ? `✗ · ${x.ok}/${x.n}` : `${ms(x.seen)} (${ms(x.seen90)}) · ${x.ok}/${x.n}`;
})]));

out.push('## Tool answered in', '', 'Median time until the tool call returned (including the extra calls the step needed).', '');
table(['Step', ...tools], steps.map((s) => [s, ...tools.map((t) => { const x = stat(t, s); return x ? ms(x.ms) : 'n/a'; })]));

out.push('## Calls and context per step', '', 'Median tool calls the step took, and bytes returned to the agent.', '');
table(['Step', ...tools], steps.map((s) => [s, ...tools.map((t) => { const x = stat(t, s); return x ? `${x.calls} · ${kb(x.bytes)}` : 'n/a'; })]));

const IOS = platform === 'ios';
const notes = [
  '- **n/a** means the tool has no way to do the step. ' + (IOS
    ? 'looktap: no iOS home button or terminate command. ios-simulator-mcp: no home button. MobileBuildMCP: taps take an element ref only (no x,y), and no open-URL tool.'
    : 'looktap: no terminate command (`launch` restarts the app).'),
  "- **looktap MCP actions return the settled screen** by default (`ls: false` turns it off): one call does the action, waits for the animation to finish and reads the next screen, which the other tools need a second call for. That wait is in its times.",
  '- **Reaction time measures the UI state** the oracle reads (accessibility tree, activity and fragments), which can change before an animation has finished drawing.',
  '- **Written by looktap\'s author.** The scenario and every adapter are mine, and looktap was developed on this app. The adapters are in `bench/adapters-ios.mjs` and `android.mjs`; corrections from the other tools\' authors are welcome.',
  '- **Failures were not re-run.** A step was re-run only when the benchmark itself was at fault (listed below), never because a tool failed.',
  '- The Mac was not otherwise idle (other apps running); every tool waited for the same idle level before it started, and the level at its start is listed below.',
  ...(IOS ? [
    "- **Appium (raw and MCP)** used a WebDriverAgent built once beforehand (`usePrebuiltWDA`): Appium's own per-session `xcodebuild` fails with code 65 on this Mac (Xcode 26.0.1). Raw Appium ran from the same Appium install appium-mcp uses (Appium 3.5.2, xcuitest 12.1.0), so only the MCP layer differs.",
    '- **Maestro, iOS:** `back` is Android-only, so back taps the navigation button by its label.',
    '- **idb swipes** are unreliable on iOS 26 (they sometimes do nothing), which also fails scroll-to steps built on them. ios-simulator-mcp uses idb underneath.',
    "- **Appium MCP's screenshot** saves the PNG to a file and returns its path, plus an HTML viewer resource with the image embedded (the bytes counted). Whether a client passes that resource to the model depends on the client.",
    '- **Fill** on iOS 26 Settings: while the search field is being edited iOS leaves it out of the accessibility tree, so the oracle accepts the typed text anywhere on screen (the results read “No Results for “wifi””).',
    '- **The Simulator window was open** for every tool (the runner reopens it after each reboot).',
    "- **MobileBuildMCP** ran with `MOBILEBUILDMCP_ENABLED_WORKFLOWS=simulator,ui-automation`; its definitions size is for that set.",
  ] : [
    '- **Fill opens a second screen:** tapping “Search Settings” starts the search activity, then the text goes into its field. Between those two calls the runner waits 2 s, not counted, for the model\'s turn: fired within milliseconds, the text arrived before the field was ready, which no agent does. Maestro does both in one call and waits by itself. Tools that can\'t wait for the field look for it (each look is a call); Appium finds the field again and retries if setting it fails.',
    '- **mobile-mcp** names an emulator by its AVD (`Pixel_9a`), not its adb serial.',
    "- **Terminate:** Appium's `mobile: terminateApp` (used by Appium MCP and raw Appium) answered success, but Settings was still running 8 s later; a plain `adb shell am force-stop` leaves it stopped. Maestro's `stopApp` did the same in 2 of 10 runs. These count as failures: the app was not stopped.",
    "- **`uiautomator dump`** (how mobile-mcp and raw adb read the screen) waits for the UI to go idle first, so a read right after an animation takes ~5 s on Android 16.",
    "- **On-device numbers** come from sampling the device's `ps` once a second, so one-shot commands shorter than that can be missed. For mobile-mcp none were caught: its on-device cost is unknown, not zero.",
    '- **Scroll to label** (to “System”) is checked by the list having moved: `dumpsys` shows no text, so whether the row is fully on screen relies on the tool.',
    '- **The emulator was rebooted** (`adb reboot`) before every tool, and its window stayed open.',
    "- **Raw Appium** ran from the same Appium install appium-mcp uses (Appium 3.5.2, UiAutomator2 driver 8.1.0), so only the MCP layer differs.",
  ]),
];
out.push('## Notes', '', ...notes, '');
const reruns = tools.flatMap((t) => {
  const e = Object.entries(R.tools[t].rerun || {});
  // a whole tool re-run for one reason: one line
  if (e.length === steps.length && new Set(e.map(([, r]) => r.why)).size === 1) return [`- **${t}**, all steps: ${e[0][1].why} (re-run ${e[0][1].date.slice(0, 10)})`];
  return e.map(([s, r]) => `- **${t}**, ${s}: ${r.why} (re-run ${r.date.slice(0, 10)})`);
});
if (reruns.length) out.push('Re-run after a fix to the benchmark (not to the tool):', '', ...reruns, '');
const shared = tools.map((t) => R.tools[t].usage?.sharedPeakRssMb).filter((x) => x != null);
if (shared.length) out.push(`Shared daemons (\`idb_companion\`, the adb server), used by several tools and by the oracle, are not counted in any tool's RAM: up to ${Math.max(...shared)} MB.`, '');
out.push(`Idle Mac before the runs: ${R.meta.idleBusyPct}% CPU busy, ${R.meta.idleFreeMb} MB reclaimable. Busy % when each tool started: ${tools.map((t) => `${t} ${R.tools[t].hostBefore?.busyPct}%`).join(', ')}.`);
const md = out.join('\n') + '\n';
writeFileSync(join(import.meta.dirname, 'results', `${platform}.md`), md);
console.log(md);
