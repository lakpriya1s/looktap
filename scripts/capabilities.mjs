// Rewrite the README's platform table from lib/capabilities.js: npm run docs:capabilities
import { readFileSync, writeFileSync } from 'node:fs';

import { capabilityTable } from '../lib/capabilities.js';

const README = new URL('../README.md', import.meta.url);
const START = '<!-- capabilities: generated by npm run docs:capabilities -->';
const END = '<!-- /capabilities -->';

/** The README with the table between the markers replaced. */
export function withTable(readme) {
  const a = readme.indexOf(START), b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error(`README.md has no ${START} … ${END} block`);
  return `${readme.slice(0, a + START.length)}\n${capabilityTable()}\n${readme.slice(b)}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(README, withTable(readFileSync(README, 'utf8')));
  console.log('README.md: platform table updated');
}
